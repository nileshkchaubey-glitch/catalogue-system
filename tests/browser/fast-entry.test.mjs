import assert from "node:assert/strict";
import test from "node:test";
import { createLocalFixture, owners } from "./local-fixture.mjs";
import { launchChromium, waitFor } from "./chromium.mjs";
const button = label => '[...document.querySelectorAll("button")].find(e=>e.textContent.trim()===' + JSON.stringify(label) + ' && !e.disabled && e.getClientRects().length)';
const dialog = 'document.querySelector("dialog[open]")';
const name = 'document.querySelector("dialog input[autofocus]") || [...document.querySelectorAll("dialog label")].find(e=>e.textContent.trim().startsWith("Product name"))?.querySelector("input")';
test("Fast Entry saves consecutive drafts, preserving category, units and price history", {timeout:45000}, async t=>{
  const app=await createLocalFixture(t);
  const browser=await launchChromium();
  const owner=owners.desktop;
  const page=await browser.newPage(app.origin,{width:1366,height:900});
  t.after(async()=>{try{await page.close();}finally{await browser.close();}});
  await page.navigate();
  await waitFor(()=>page.visible(button("Sign in")),"sign-in form");
  await page.focus('document.querySelector("input[name=email]")');
  await page.type(owner.email);
  await page.focus('document.querySelector("input[name=password]")');
  await page.type(owner.password);
  await page.click(button("Sign in"));
  await waitFor(()=>page.visible(button("Fast Entry")),"Fast Entry button");
  await page.click(button("Fast Entry"));
  await waitFor(()=>page.visible(dialog),"Fast Entry dialog");
  await page.focus(name);
  await page.type("Synthetic quick tray");
  await page.focus('document.querySelector(".fast-entry-row input")');
  await page.type("250 ml");
  await page.focus('document.querySelectorAll(".fast-entry-row input")[1]');
  await page.type("4.25");
  await page.focus('document.querySelectorAll(".fast-entry-row input")[2]');
  await page.type("5.50");
  await page.click(button("Save & Next"));
  await waitFor(async()=>await page.evaluate('document.body.innerText.includes("Saved. Enter the next product.")'),"save and next");
  assert.equal(await page.evaluate('(' + name + ').value'),"");
  await page.focus(name);
  await page.type("Synthetic second tray");
  await page.click(button("Save Draft"));
  await waitFor(async()=>!(await page.visible(dialog)),"second draft saved");
  const products=app.rows.get(owner.id).document.families;
  const a=products.find(f=>f.name==="Synthetic quick tray"),b=products.find(f=>f.name==="Synthetic second tray");
  assert.ok(a&&b);
  assert.equal(a.category,b.category);
  assert.equal(a.variants[0].purchase,"4.25");
  assert.equal(a.variants[0].rate,"5.50");
  assert.equal(a.variants[0].ready,false);
  assert.equal(a.variants[0].history.length,1);
  assert.equal(b.variants[0].rate,"");
  assert.notEqual(a.variants[0].id,b.variants[0].id);
  assert.deepEqual(page.errors,[]);
});
